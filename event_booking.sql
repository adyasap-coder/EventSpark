CREATE TABLE EVENT(
E_ID INT AUTO_INCREMENT PRIMARY KEY,
E_Name VARCHAR(100),
E_Date DATE,
Venue VARCHAR(100),
Ticket_Price DECIMAL(10,2),
Category_ID INT,
FOREIGN KEY(Category_ID) REFERENCES EVENT_CATEGORY(Category_ID)
);
