CREATE TABLE SEAT(
Seat_ID INT AUTO_INCREMENT PRIMARY KEY,
E_ID INT,
Seat_No VARCHAR(10),
FOREIGN KEY(E_ID) REFERENCES EVENT(E_ID)
);
INSERT INTO SEAT VALUES
